// The npm package ships only the files listed in package.json `files`. Every
// local module the compiled CLI can load must be listed, or
// `npm install -g listener-ai` fails at start-up with `Cannot find module`
// for EVERY command (a missing transitive module breaks the top-level require
// graph). This walks the compiled require graph from dist/cli.js.

import assert from 'node:assert/strict';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { describe, it } from 'node:test';

const distDir = __dirname;
const root = path.join(distDir, '..');

function localRequires(file: string): string[] {
  const source = fs.readFileSync(file, 'utf-8');
  const out: string[] = [];
  for (const match of source.matchAll(/require\(["'](\.{1,2}\/[^"']+)["']\)/g)) {
    const base = path.resolve(path.dirname(file), match[1]);
    const candidate = base.endsWith('.js') ? base : `${base}.js`;
    out.push(candidate);
  }
  return out;
}

describe('npm package files whitelist', () => {
  it('lists every local module reachable from dist/cli.js', () => {
    const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf-8')) as {
      files: string[];
    };
    const listed = new Set(pkg.files);
    const seen = new Set<string>();
    const queue = [path.join(distDir, 'cli.js')];
    while (queue.length > 0) {
      const file = queue.shift()!;
      if (seen.has(file)) continue;
      seen.add(file);
      // buildConstants.js is generated by the build and listed explicitly.
      if (!fs.existsSync(file)) continue;
      queue.push(...localRequires(file));
    }
    const missing = [...seen]
      .map((f) => path.relative(root, f).split(path.sep).join('/'))
      .filter((rel) => !listed.has(rel));
    assert.deepEqual(missing, [], `add these to package.json files: ${missing.join(', ')}`);
    assert.ok(seen.has(path.join(distDir, 'services', 'googleSession.js')));
  });
});
